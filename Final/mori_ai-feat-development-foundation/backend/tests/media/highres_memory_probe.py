"""Synthetic 40MP normalization with the real 512MiB child RSS guard.

Run in an isolated --memory=1g --memory-swap=1g container, no network required.
Each fixture is generated by a separate process so fixture allocation cannot
hide a normalization leak or inflate the measured normalizer child RSS.
"""
import asyncio
import json
from pathlib import Path
import resource
import subprocess
import sys
import tempfile
import time

from backend.media.process import normalize_in_process, CHILD_RSS_LIMIT
from backend.media import process


def fixture(path, kind):
    from PIL import Image
    if kind == 'jpeg':
        image = Image.effect_noise((8000, 5000), 32).convert('RGB')
        image.save(path, format='JPEG', quality=70)
    else:
        alpha = kind.startswith('alpha')
        size = (6324, 6324) if kind == 'alpha_square' else (6000, 6666)
        image = Image.new('RGBA' if alpha else 'RGB', size, (20, 80, 140, 100) if alpha else (20, 80, 140))
        for x in range(0, size[0] - 64, 128):
            image.paste((140, 80, 20, 220) if alpha else (140, 80, 20), (x, 0, x + 64, size[1]))
        exif = Image.Exif(); exif[274] = 6
        image.save(path, format='PNG', exif=exif)
    image.close()


async def main():
    with tempfile.TemporaryDirectory(prefix='mori-highres-') as directory:
        for kind in ('jpeg', 'rgb', 'alpha', 'alpha_square'):
            path = Path(directory) / kind
            subprocess.run([sys.executable, '-m', __spec__.name, str(path), kind], check=True)
            assert path.stat().st_size <= 20 * 1024 * 1024
            tick = time.monotonic()
            peak = 0
            original_rss = process._rss
            def measure(pid):
                nonlocal peak
                rss = original_rss(pid)
                peak = max(peak, rss)
                return rss
            process._rss = measure
            try:
                result = await normalize_in_process(path, kind)
            finally:
                process._rss = original_rss
            assert max(result.width, result.height) <= 4096
            assert not result.input_is_3_4
            from PIL import Image
            from io import BytesIO
            with Image.open(BytesIO(result.webp_bytes)) as image:
                image.load()
                assert image.mode == ('RGBA' if kind.startswith('alpha') else 'RGB')
                assert not image.getexif()
            print(json.dumps({'kind': kind, 'source_bytes': path.stat().st_size,
                'output_bytes': len(result.webp_bytes), 'size': [result.width, result.height],
                'seconds': round(time.monotonic() - tick, 3),
                'normalizer_sampled_peak_bytes': peak,
                'children_peak_rss_kib': resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss}), flush=True)
        cg = Path('/sys/fs/cgroup')
        events = dict(line.split() for line in (cg/'memory.events').read_text().splitlines())
        summary = {'guard_bytes': CHILD_RSS_LIMIT, 'container_peak_bytes': int((cg/'memory.peak').read_text()), 'events': events}
        print('HIGHRES_MEMORY ' + json.dumps(summary), flush=True)
        assert int(events['oom_kill']) == 0
        assert resource.getrusage(resource.RUSAGE_CHILDREN).ru_maxrss * 1024 < CHILD_RSS_LIMIT
        assert summary['container_peak_bytes'] < 1024**3 * .8


if __name__ == '__main__':
    if len(sys.argv) == 3:
        fixture(Path(sys.argv[1]), sys.argv[2])
    else:
        asyncio.run(main())
